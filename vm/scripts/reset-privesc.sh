#!/usr/bin/env bash
# reset-privesc.sh — runs ON THE HOST. Restores the Phase 5 privilege-
# escalation weakness to its clean starting state, and removes any
# artifacts a player/team may have left behind while exploiting it
# (e.g. a SUID shell copy in /tmp). Safe to re-run between teams.
set -euo pipefail
cd "$(dirname "$0")/.."

KEY="keys/ctfbuilder_ed25519"
PORT=2222
HOST="ctfbuilder@127.0.0.1"
SSH_OPTS=(-i "$KEY" -p "$PORT" -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/dev/null -o ConnectTimeout=10)

if ! ssh "${SSH_OPTS[@]}" "$HOST" 'echo ok' >/dev/null 2>&1; then
  echo "Cannot reach the VM over SSH. Is it booted?" >&2
  exit 1
fi

ssh "${SSH_OPTS[@]}" "$HOST" bash -s <<'REMOTE'
set -euo pipefail

echo "== Restoring /opt/admin-tools/cleanup.sh to its clean content =="
sudo tee /opt/admin-tools/cleanup.sh >/dev/null <<'EOF'
#!/bin/bash
# Housekeeping for admin-tools cache (auto-generated by the deploy
# pipeline -- edits here are picked up by cron within a minute).
mkdir -p /var/cache/admin-tools
find /var/cache/admin-tools -type f -mtime +1 -delete 2>/dev/null
EOF
sudo chown root:admin /opt/admin-tools/cleanup.sh
sudo chmod 664 /opt/admin-tools/cleanup.sh

echo "== Clearing any artifacts a team may have left behind =="
# Common things a successful exploit leaves lying around: a SUID shell
# copy, a reverse-shell helper, cache files. Remove anything under
# these known, bounded locations -- never a general-purpose /tmp wipe.
sudo rm -f /tmp/rootbash /tmp/rootshell /tmp/*.suid 2>/dev/null || true
sudo rm -rf /var/cache/admin-tools
sudo truncate -s 0 /var/log/admin-tools-cleanup.log

echo "== Verifying clean state =="
stat -c "cleanup.sh: %a %U:%G" /opt/admin-tools/cleanup.sh
test -e /tmp/rootbash && echo "WARNING: /tmp/rootbash still present" || echo "OK: no leftover SUID shell"
REMOTE

echo "Done. Privesc mechanism reset to its clean starting state."
